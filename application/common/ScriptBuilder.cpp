QString libraryFileName() {
#if defined(Q_OS_WIN)
    return QStringLiteral("game.dll");
#elif defined(Q_OS_MACOS)
    return QStringLiteral("game.dylib");
#else
    return QStringLiteral("game.so");
#endif
}

/// CMake script of the game library. Paths are passed in as cache variables, so the file
/// never changes and CMake reconfigures only when the scripts folder gains or loses files.
const char* kCMakeLists = R"(# Generated by the Lumora editor - do not edit. Rebuilt from the project's Scripts/ folder.
cmake_minimum_required(VERSION 3.20)
project(LumoraGame LANGUAGES CXX)
set(CMAKE_CXX_STANDARD 20)
set(CMAKE_CXX_STANDARD_REQUIRED ON)
set(CMAKE_POSITION_INDEPENDENT_CODE ON)
file(GLOB_RECURSE LUMORA_GAME_SOURCES CONFIGURE_DEPENDS "${LUMORA_SCRIPTS_DIR}/*.cpp")
add_library(game MODULE ${LUMORA_GAME_SOURCES} "${CMAKE_CURRENT_LIST_DIR}/lumora_module.cpp")
target_include_directories(game PRIVATE "${LUMORA_SDK_INCLUDE_DIR}" "${LUMORA_SCRIPTS_DIR}")
# One folder for every generator and configuration ($<1:...> stops multi-config subfolders).
set_target_properties(game PROPERTIES PREFIX "" OUTPUT_NAME game
    LIBRARY_OUTPUT_DIRECTORY "$<1:${LUMORA_OUTPUT_DIR}>"
    RUNTIME_OUTPUT_DIRECTORY "$<1:${LUMORA_OUTPUT_DIR}>")
if(MSVC)
    target_compile_options(game PRIVATE /W3 /EHsc /utf-8)
else()
    # Hidden symbols: only the lumora_script_* entry points leave the library, so a reloaded
    # generation never binds to the previous one. No GNU_UNIQUE symbols, or dlclose could not
    # unload an old generation.
    target_compile_options(game PRIVATE -Wall -fvisibility=hidden -fvisibility-inlines-hidden)
    if(CMAKE_CXX_COMPILER_ID STREQUAL "GNU")
        target_compile_options(game PRIVATE -fno-gnu-unique)
    endif()
endif()
)";

const char* kModuleMain = R"(// Generated by the Lumora editor: the game library's entry points.
#include <lumora/ScriptModuleMain.hpp>
)";

const char* kBehaviourTemplate = R"(#include <lumora/Script.hpp>

using namespace lumora::script;

// Add a Script component with Behaviour "%1" to an entity, then press Play.
// Saving this file rebuilds the game and reloads it, also while playing.
class %1 : public Behaviour {
public:
    void start() override {
        origin_ = position();
        log("%1 started on " + name());
    }

    void update(float dt) override {
        elapsed_ += dt;
        // Example: float up and down around the starting point.
        setPosition(origin_ + Vec3{0.0f, std::sin(elapsed_ * 2.0f) * 0.25f, 0.0f});
    }

private:
    Vec3 origin_;
    float elapsed_ = 0.0f;
};

LUMORA_BEHAVIOUR(%1);
)";

bool writeIfChanged(const QString& path, const QByteArray& content, QString* error) {
    QFile existing(path);
    if (existing.open(QIODevice::ReadOnly) && existing.readAll() == content) return true;
    existing.close();
    QFile out(path);
    if (!out.open(QIODevice::WriteOnly | QIODevice::Truncate) || out.write(content) != content.size()) {
        if (error != nullptr) *error = QObject::tr("cannot write %1: %2").arg(path, out.errorString());
        return false;
    }
    return true;
}

