ScriptBuilder::ScriptBuilder(QString projectRoot, QObject* parent) : QObject(parent), root_(std::move(projectRoot)) {
    debounce_.setSingleShot(true);
    debounce_.setInterval(400);  // editors save in bursts (temp file, rename, chmod)
    connect(&debounce_, &QTimer::timeout, this, &ScriptBuilder::build);
    connect(&watcher_, &QFileSystemWatcher::fileChanged, this, [this] {
        rewatch();  // editors that save by rename replace the watched file
        debounce_.start();
    });
    connect(&watcher_, &QFileSystemWatcher::directoryChanged, this, [this] {
        rewatch();
        debounce_.start();
    });
}

ScriptBuilder::~ScriptBuilder() {
    if (process_ != nullptr) {
        process_->kill();
        process_->waitForFinished(3000);
    }
}

QString ScriptBuilder::scriptsDir() const { return QDir(root_).filePath(QStringLiteral("Scripts")); }
QString ScriptBuilder::buildDir() const { return QDir(root_).filePath(QStringLiteral("Saved/ScriptBuild")); }
QString ScriptBuilder::libraryPath() const { return QDir(buildDir()).filePath(QStringLiteral("bin/") + libraryFileName()); }
QString ScriptBuilder::loadDir() const { return QDir(buildDir()).filePath(QStringLiteral("loaded")); }

bool ScriptBuilder::hasScripts() const {
    QDirIterator it(scriptsDir(), {QStringLiteral("*.cpp")}, QDir::Files, QDirIterator::Subdirectories);
    return it.hasNext();
}

QString ScriptBuilder::sdkIncludeDir() {
    QStringList candidates;
    candidates << QDir(QCoreApplication::applicationDirPath()).filePath(QStringLiteral("../include"))
               << QDir(QCoreApplication::applicationDirPath()).filePath(QStringLiteral("include"));
#if defined(LUMORA_SDK_INCLUDE_DIR)
    candidates << QStringLiteral(LUMORA_SDK_INCLUDE_DIR);
#endif
    for (const QString& dir : candidates) {
        if (QFileInfo::exists(QDir(dir).filePath(QStringLiteral("lumora/Script.hpp")))) return QDir(dir).absolutePath();
    }
    return {};
}

bool ScriptBuilder::createBehaviour(const QString& className, QString* error) {
    static const QRegularExpression identifier(QStringLiteral("^[A-Za-z_][A-Za-z0-9_]*$"));
    if (!identifier.match(className).hasMatch()) {
        if (error != nullptr) *error = tr("'%1' is not a valid C++ class name.").arg(className);
        return false;
    }
    if (!QDir().mkpath(scriptsDir())) {
        if (error != nullptr) *error = tr("cannot create %1").arg(scriptsDir());
        return false;
    }
    const QString path = QDir(scriptsDir()).filePath(className + QStringLiteral(".cpp"));
    if (QFileInfo::exists(path)) {
        if (error != nullptr) *error = tr("%1 already exists.").arg(path);
        return false;
    }
    return writeIfChanged(path, QString::fromLatin1(kBehaviourTemplate).arg(className).toUtf8(), error);
}

bool ScriptBuilder::prepareSources(QString* error) {
    if (sdkIncludeDir().isEmpty()) {
        if (error != nullptr) *error = tr("The Lumora SDK headers (include/lumora/Script.hpp) are missing next to the editor.");
        return false;
    }
    const QString src = QDir(buildDir()).filePath(QStringLiteral("src"));
    if (!QDir().mkpath(src) || !QDir().mkpath(QDir(buildDir()).filePath(QStringLiteral("bin")))) {
        if (error != nullptr) *error = tr("cannot create %1").arg(buildDir());
        return false;
    }
    return writeIfChanged(QDir(src).filePath(QStringLiteral("CMakeLists.txt")), kCMakeLists, error) &&
           writeIfChanged(QDir(src).filePath(QStringLiteral("lumora_module.cpp")), kModuleMain, error);
}

QStringList ScriptBuilder::configureArguments() const {
    QStringList args{QStringLiteral("-S"), QDir(buildDir()).filePath(QStringLiteral("src")), QStringLiteral("-B"),
                     QDir(buildDir()).filePath(QStringLiteral("obj")),
                     QStringLiteral("-DCMAKE_BUILD_TYPE=RelWithDebInfo"),
                     QStringLiteral("-DLUMORA_SCRIPTS_DIR=") + QDir(scriptsDir()).absolutePath(),
                     QStringLiteral("-DLUMORA_SDK_INCLUDE_DIR=") + sdkIncludeDir(),
                     QStringLiteral("-DLUMORA_OUTPUT_DIR=") + QDir(QDir(buildDir()).filePath(QStringLiteral("bin"))).absolutePath()};
    // Ninja when available (fast no-op builds); otherwise CMake's default generator.
    if (!QFileInfo::exists(QDir(buildDir()).filePath(QStringLiteral("obj/CMakeCache.txt"))) &&
        !QStandardPaths::findExecutable(QStringLiteral("ninja")).isEmpty()) {
        args << QStringLiteral("-G") << QStringLiteral("Ninja");
    }
    return args;
}

void ScriptBuilder::build() {
    if (process_ != nullptr) {
        queued_ = true;
        return;
    }
    output_.clear();
    emit buildStarted();
    QString error;
    if (!hasScripts()) {
        output_ = tr("No scripts: add .cpp files to %1.").arg(QDir::toNativeSeparators(scriptsDir()));
        finish(false);
        return;
    }
    if (QStandardPaths::findExecutable(QStringLiteral("cmake")).isEmpty()) {
        output_ = tr("CMake was not found. Install CMake and a C++20 compiler (GCC, Clang or Visual Studio) to build scripts.");
        finish(false);
        return;
    }
    if (!prepareSources(&error)) {
        output_ = error;
        finish(false);
        return;
    }
    // Configure every time: cheap when nothing changed, and it picks up new script files.
    pendingSteps_ = {QStringLiteral("configure"), QStringLiteral("build")};
    log::info("Script", "building scripts in {}", scriptsDir().toStdString());
    runNext();
}

void ScriptBuilder::runNext() {
    if (pendingSteps_.isEmpty()) {
        finish(true);
        return;
    }
    const QString step = pendingSteps_.takeFirst();
    QStringList args = step == QLatin1String("configure")
                           ? configureArguments()
                           : QStringList{QStringLiteral("--build"), QDir(buildDir()).filePath(QStringLiteral("obj")),
                                         QStringLiteral("--config"), QStringLiteral("RelWithDebInfo")};
    process_ = new QProcess(this);
    process_->setProcessChannelMode(QProcess::MergedChannels);
    connect(process_, &QProcess::readyRead, this, [this] { output_ += QString::fromLocal8Bit(process_->readAll()); });
    connect(process_, &QProcess::finished, this, [this](int code, QProcess::ExitStatus status) {
        output_ += QString::fromLocal8Bit(process_->readAll());
        process_->deleteLater();
        process_ = nullptr;
        if (status != QProcess::NormalExit || code != 0) {
            finish(false);
        } else {
            runNext();
        }
    });
    connect(process_, &QProcess::errorOccurred, this, [this](QProcess::ProcessError e) {
        if (e != QProcess::FailedToStart || process_ == nullptr) return;
        output_ += tr("cannot start cmake: %1").arg(process_->errorString());
        process_->deleteLater();
        process_ = nullptr;
        finish(false);
    });
    process_->start(QStandardPaths::findExecutable(QStringLiteral("cmake")), args);
}

void ScriptBuilder::finish(bool ok) {
    pendingSteps_.clear();
    if (ok) {
        log::info("Script", "scripts built: {}", libraryPath().toStdString());
    } else {
        log::warn("Script", "script build failed:\n{}", output_.trimmed().right(4000).toStdString());
    }
    emit buildFinished(ok, output_);
    if (queued_) {
        queued_ = false;
        QTimer::singleShot(0, this, &ScriptBuilder::build);
    }
}

bool ScriptBuilder::buildBlocking(QString* output, int timeoutMs) {
    bool result = false;
    bool done = false;
    QEventLoop loop;
    auto connection = connect(this, &ScriptBuilder::buildFinished, &loop, [&](bool ok, const QString& log) {
        result = ok;
        done = true;
        if (output != nullptr) *output = log;
        loop.quit();
    });
    QTimer::singleShot(timeoutMs, &loop, &QEventLoop::quit);
    build();
    if (!done) loop.exec();
    disconnect(connection);
    if (!done && output != nullptr) *output = tr("script build timed out");
    return result && done;
}

void ScriptBuilder::setWatching(bool watching) {
    watching_ = watching;
    if (!watching) {
        if (!watcher_.files().isEmpty()) watcher_.removePaths(watcher_.files());
        if (!watcher_.directories().isEmpty()) watcher_.removePaths(watcher_.directories());
        return;
    }
    QDir().mkpath(scriptsDir());
    rewatch();
}

void ScriptBuilder::rewatch() {
    if (!watching_) return;
    QStringList paths{scriptsDir()};
    QDirIterator it(scriptsDir(), {QStringLiteral("*.cpp"), QStringLiteral("*.hpp"), QStringLiteral("*.h")},
                    QDir::Files | QDir::Dirs | QDir::NoDotAndDotDot, QDirIterator::Subdirectories);
    while (it.hasNext()) paths << it.next();
    QStringList missing;
    for (const QString& p : paths) {
        if (!watcher_.files().contains(p) && !watcher_.directories().contains(p)) missing << p;
    }
    if (!missing.isEmpty()) watcher_.addPaths(missing);
}

